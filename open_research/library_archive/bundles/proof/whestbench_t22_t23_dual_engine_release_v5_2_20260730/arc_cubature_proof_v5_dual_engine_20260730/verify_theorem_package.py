from __future__ import annotations

"""Recompute and verify every theorem-critical low-cost artifact.

The expensive 1,421-subinterval curvature certificate is regenerated by
FULL_PROOF_REPRODUCE.sh.  This verifier reassembles those deterministic chunks,
recomputes all scalar certificates, reruns an independent arithmetic audit, and
checks the theorem's one-sided logic.  It never rewrites the hash manifest.
"""

import json
import subprocess
import sys
from decimal import Decimal
from fractions import Fraction
from pathlib import Path

BASE=Path(__file__).resolve().parent
RES=BASE/'results'


def run(name:str)->None:
    subprocess.run([sys.executable,str(BASE/name)],cwd=BASE,check=True,stdout=subprocess.DEVNULL)


def main()->None:
    run('assemble_formal_certificate.py')
    run('audit_formal_interval_arithmetic.py')
    run('verify_sign_logic.py')
    run('generate_kerdock_multiplicity.py')
    run('formal_kernel_mean.py')
    run('formal_delsarte_bound.py')
    run('formal_near_optimality_theorem.py')

    pointwise=json.loads((RES/'FORMAL_CERTIFICATE_D256_L32.json').read_text())
    sign=json.loads((RES/'FORMAL_SIGN_LOGIC_AUDIT.json').read_text())
    audit=json.loads((RES/'FORMAL_INTERVAL_AUDIT.json').read_text())
    mult=json.loads((RES/'KERDOCK_MULTIPLICITY_PROOF.json').read_text())
    mean=json.loads((RES/'FORMAL_KERNEL_MEAN_D256_L32.json').read_text())
    energy=json.loads((RES/'FORMAL_DELSARTE_BOUND_D256_L32.json').read_text())
    theorem=json.loads((RES/'FORMAL_NEAR_OPTIMALITY_THEOREM_D256_L32.json').read_text())

    assert all(x['passed'] for x in (pointwise,sign,audit,mult,mean,energy,theorem))
    assert pointwise['coverage_exact'] and pointwise['no_gaps_or_overlaps']
    assert pointwise['mesh_original_intervals']==1079
    assert pointwise['mesh_certified_subintervals']==1421
    assert Decimal(pointwise['global_upper_bound'])<0
    assert sign['special_box_order_verified']
    assert sign['only_interior_maximum_boxes']==[0,2,4]

    assert energy['higher_coefficients_nonnegative']
    assert Fraction(energy['h1_exact'])<=1
    assert Decimal(mean['A0_width'])<Decimal('3e-22')

    counts=mult['per_fixed_node']
    assert sum(counts.values())==66048==mult['total_nodes']
    assert counts['inner_product_plus_1_over_16']==counts['inner_product_minus_1_over_16']==32768

    ratio=theorem['actual_multiplicative_ratio_kerdock_over_infimum']
    excess=theorem['actual_relative_excess_percent']
    additive=theorem['actual_additive_suboptimality']
    assert Decimal(ratio['lower'])==1
    assert Decimal(excess['lower'])==0
    assert Decimal(additive['lower'])==0
    assert Decimal(ratio['upper'])<Decimal('1.000234')
    assert Decimal(excess['upper'])<Decimal('0.023366')
    assert 'network-independent' in theorem['theorem']
    assert 'signed cubature weights' in theorem['scope']['excluded']
    assert 'finite-width network objectives' in theorem['scope']['excluded']

    out={
        'passed':True,
        'formal_pointwise_subintervals':pointwise['mesh_certified_subintervals'],
        'formal_pointwise_global_margin':pointwise['global_upper_bound'],
        'kernel_mean_width':mean['A0_width'],
        'certified_relative_excess_percent_upper':excess['upper'],
        'one_sided_logic_verified':True,
        'clean_room_note':'Run FULL_PROOF_REPRODUCE.sh to regenerate all curvature chunks before this verifier.',
    }
    (RES/'THEOREM_PACKAGE_VERIFICATION.json').write_text(json.dumps(out,indent=2))
    print(json.dumps(out,indent=2))


if __name__=='__main__':main()
