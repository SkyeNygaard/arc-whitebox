def forward_checkpoint_target(
    weights: np.ndarray,
    points: np.ndarray,
    rotation: np.ndarray,
    checkpoint: int,
    target_layer: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return checkpoint activation, target activation, and final output."""
    pre = points @ (rotation @ weights[0].astype(np.float32))
    activation = np.maximum(pre, 0.0)
    checkpoint_activation = activation.copy() if checkpoint == 0 else None
    target_activation = activation.copy() if target_layer == 0 else None
    for layer in range(1, len(weights)):
        activation = np.maximum(activation @ weights[layer], 0.0)
        if layer == checkpoint:
            checkpoint_activation = activation.copy()
        if layer == target_layer:
            target_activation = activation.copy()
    if checkpoint_activation is None or target_activation is None:
        raise ValueError((checkpoint, target_layer, len(weights)))
    return checkpoint_activation, target_activation, activation


def oracle_tail_map(
    weights: np.ndarray,
    checkpoint: int,
    target_layer: int,
    pre_mean: np.ndarray,
    pre_second: np.ndarray,
) -> np.ndarray:
    """Expected-gate row map from post-checkpoint to post-target."""
    transport = np.eye(WIDTH, dtype=np.float64)
    for layer in range(checkpoint + 1, target_layer + 1):
        transport = transport @ weights[layer].astype(np.float64)
        mean = np.asarray(pre_mean[layer], dtype=np.float64)
        variance = np.maximum(
            np.diag(np.asarray(pre_second[layer], dtype=np.float64))
            - np.square(mean),
            1e-20,
        )
        transport *= ndtr(mean / np.sqrt(variance))[None, :]
    return transport


def checkpoint_scalar_contraction(
    activation: np.ndarray,
    transport: np.ndarray,
    left: np.ndarray,
    right: np.ndarray,
) -> np.ndarray:
    """Fixed-radius K3 contractions after expected-gate transport."""
    centered = np.asarray(activation, dtype=np.float32)
    centered = centered - np.mean(centered, axis=0, dtype=np.float64)
    transported = centered @ np.asarray(transport, dtype=np.float32)
    transported -= np.mean(transported, axis=0, dtype=np.float64)
    left32 = np.asarray(left, dtype=np.float32)
    right32 = np.asarray(right, dtype=np.float32)
    return np.mean(
        (np.square(transported) @ left32) * (transported @ right32),
        axis=0,
        dtype=np.float64,
    )


def factor_scalar_contraction(
    factors: tuple[torch.Tensor, torch.Tensor, torch.Tensor],
    left: np.ndarray,
    right: np.ndarray,
) -> torch.Tensor:
    """Contract ``K[i,i,j]`` from symmetric CP factors without a dense slice."""
    a, b, c = factors
    left_t = torch.as_tensor(left, device=a.device, dtype=a.dtype).T
    right_t = torch.as_tensor(right, device=a.device, dtype=a.dtype).T
    left_ab = left_t @ (a * b)
    left_ac = left_t @ (a * c)
    left_bc = left_t @ (b * c)
    right_a = right_t @ a
    right_b = right_t @ b
    right_c = right_t @ c
    return torch.sum(
        left_ab * right_c + left_ac * right_b + left_bc * right_a,
        dim=1,
    ) / 3.0


def late_source_scalar(
    weights: np.ndarray,
    checkpoint: int,
    target_layer: int,
    post_mean: np.ndarray,
    post_second: np.ndarray,
    pre_mean: np.ndarray,
    pre_second: np.ndarray,
    left: np.ndarray,
    right: np.ndarray,
    *,
    dtype: torch.dtype,
) -> tuple[np.ndarray, dict[str, float]]:
    """Factorized sources from layers checkpoint+1..target with zero initial K3."""
    torch_weights = torch.as_tensor(
        np.asarray(weights).transpose(0, 2, 1).copy(),
        dtype=dtype,
    )
    mean0 = np.asarray(post_mean[checkpoint], dtype=np.float64)
    covariance0 = (
        np.asarray(post_second[checkpoint], dtype=np.float64)
        - np.outer(mean0, mean0)
    )
    state = coerce_input(
        {
            1: torch.as_tensor(mean0, dtype=dtype),
            2: torch.as_tensor(covariance0, dtype=dtype),
        },
        k_max=3,
        kind=SIMPLE,
    )

    started = time.perf_counter()
    with torch.no_grad(), NamedFlopCounter(strict=False) as counter:
        for layer in range(checkpoint + 1, target_layer + 1):
            pre = linear_kprop(state, torch_weights[layer], k_max=3)

            # Preserve K3/K4 transport, but inject exact K1/K2 before the
            # nonlinearity so every late gate/source sees oracle marginals.
            mean = np.asarray(pre_mean[layer], dtype=np.float64)
            covariance = (
                np.asarray(pre_second[layer], dtype=np.float64)
                - np.outer(mean, mean)
            )
            oracle_state = coerce_input(
                {
                    1: torch.as_tensor(mean, dtype=dtype),
                    2: torch.as_tensor(covariance, dtype=dtype),
                },
                k_max=3,
                kind=SIMPLE,
            )
            pre[1] = oracle_state[1]
            pre[2] = oracle_state[2]
            state = nonlin_kprop(
                pre,
                nonlin_wick_coef=relu_wick_coef,
                k_max=3,
                kind=SIMPLE,
                use_pK=True,
                factor=True,
            )

        if 3 not in state or not hasattr(state[3], "factors"):
            raise TypeError(type(state.get(3)))
        scalar = factor_scalar_contraction(
            state[3].factors,
            left,
            right,
        )

    elapsed = time.perf_counter() - started
    rank = state[3].factors[0].shape[1]
    flop_dict = counter.flop_dict()
    return (
        scalar.detach().cpu().numpy().astype(np.float64),
        {
            "seconds": elapsed,
            "factor_rank": int(rank),
            "torch_flops": int(counter.total()),
            "torch_residual_flops": int(flop_dict.get("resid", 0)),
            "torch_flop_breakdown": {
                key: int(value)
                for key, value in sorted(
                    flop_dict.items(),
                    key=lambda item: -item[1],
                )
            },
        },
    )


def analytical_extra_flops(
    factor_flops: int,
    *,
    checkpoint: int,
    target_layer: int,
    rank: int,
) -> dict[str, int]:
    """Conservative per-network extra FLOPs beyond the Kerdock forward pass."""
    point_count = N_BASES * ROWS_PER_BASIS
    tail_layers = target_layer - checkpoint
    tail_map = 2 * tail_layers * WIDTH**3
    checkpoint_transport = 2 * point_count * WIDTH**2
    # One construction of the two rank-k target control features.
    target_features = (
        point_count * WIDTH
        + 4 * point_count * WIDTH * rank
        + point_count * rank
    )
    total = factor_flops + tail_map + checkpoint_transport + target_features
    return {
        "factorized_tail_and_scalar": int(factor_flops),
        "expected_gate_tail_map": int(tail_map),
        "checkpoint_cloud_transport": int(checkpoint_transport),
        "target_control_features": int(target_features),
        "total_extra": int(total),
    }


def summarize(records: list[dict]) -> dict:
    baseline = np.asarray([record["baseline_mse"] for record in records])
    labels = list(records[0]["method_mses"])
    result = {}
    for label in labels:
        mse = np.asarray([r["method_mses"][label] for r in records])
        result[label] = {
            "mse_ratio": float(np.mean(mse) / np.mean(baseline)),
            "wins": int(np.sum(mse < baseline)),
            "worst": float(np.max(mse / baseline)),
            "mean_anchor_error_relative_to_same_cloud": (
                0.0
                if label == "oracle"
                else float(
                    np.mean(
                        [
                            r["anchor_diagnostics"][label][
                                "relative_to_same_cloud"
                            ]
                            for r in records
                        ]
                    )
                )
            ),
        }
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--indices",
        type=int,
        nargs="+",
        default=list(range(160, 168)),
    )
    parser.add_argument("--checkpoint", type=int, default=20)
    parser.add_argument("--target-layer", type=int, default=29)
    parser.add_argument("--rotation-seed", type=int, default=3)
    parser.add_argument("--rank", type=int, default=2)
    parser.add_argument("--folds", type=int, default=6)
    parser.add_argument("--ridge", type=float, default=0.1)
    parser.add_argument(
        "--inherited-scales",
        type=float,
        nargs="+",
        default=[0.5, 0.75, 1.0, 1.25],
    )
    parser.add_argument(
        "--dtype",
        choices=["float32", "float64"],
        default="float32",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=(
            HERE
            / "results"
            / "late_source_scalar_checkpoint20_selection8.json"
        ),
    )
    args = parser.parse_args()
    if args.rank != 2:
        raise ValueError("This bounded experiment predeclares rank=2")
    if not 0 <= args.checkpoint < args.target_layer:
        raise ValueError((args.checkpoint, args.target_layer))
    dtype = torch.float32 if args.dtype == "float32" else torch.float64

    points = make_kerdock_design()
    rotation = random_rotation(WIDTH, args.rotation_seed)
    radius = sphere_radius_mean(WIDTH)
    rows = _load_rows(FULL_DATA, args.indices)
    records = []

    for index, (name, weights, targets) in zip(args.indices, rows, strict=True):
        started = time.perf_counter()
        checkpoint_activation, target_activation, final = (
            forward_checkpoint_target(
                weights,
                points,
                rotation,
                args.checkpoint,
                args.target_layer,
            )
        )
        left, right, _ = empirical_c21_state(
            target_activation,
            args.rank,
        )
        sample_mean = np.mean(target_activation, axis=0, dtype=np.float64)

        with np.load(moment_path(index)) as oracle:
            post_mean = np.asarray(oracle["mean"], dtype=np.float64)
            post_second = np.asarray(oracle["M11"], dtype=np.float64)
            pre_mean = np.asarray(oracle["pre_mean"], dtype=np.float64)
            pre_second = np.asarray(oracle["pre_M11"], dtype=np.float64)
            target_mean = post_mean[args.target_layer]
            target_second = post_second[args.target_layer]
            true_raw_m21 = np.asarray(
                oracle["M21"][args.target_layer],
                dtype=np.float64,
            )
            target_marginal_second = np.asarray(
                oracle["m2"][args.target_layer],
                dtype=np.float64,
            )
            true_c21 = connected_m21(
                target_mean,
                target_second,
                true_raw_m21,
                target_marginal_second,
            )

        tail_map = oracle_tail_map(
            weights,
            args.checkpoint,
            args.target_layer,
            pre_mean,
            pre_second,
        )
        inherited_fixed_scalar = checkpoint_scalar_contraction(
            checkpoint_activation,
            tail_map,
            left,
            right,
        )
        # Gaussian K3 / (d+1) equals fixed-radius K3 / E[R]^2.
        inherited_anchor_contribution = (
            inherited_fixed_scalar / np.square(radius)
        )
        late_scalar, late_diagnostics = late_source_scalar(
            weights,
            args.checkpoint,
            args.target_layer,
            post_mean,
            post_second,
            pre_mean,
            pre_second,
            left,
            right,
            dtype=dtype,
        )
        late_anchor_contribution = late_scalar / (WIDTH + 1.0)

        true_c21_contribution = contraction(left, true_c21, right)
        predicted_connected_anchors = {
            "checkpoint_sample_only": inherited_anchor_contribution,
            "late_source_only": late_anchor_contribution,
        }
        for scale in args.inherited_scales:
            predicted_connected_anchors[
                f"combined_inherited_scale{scale:g}"
            ] = (
                late_anchor_contribution
                + scale * inherited_anchor_contribution
            )

        centers = {
            "oracle_center": target_mean,
            "sample_center": sample_mean,
        }
        pointwise = {
            label: contracted_pointwise(
                target_activation,
                left,
                right,
                center,
                radius,
            )
            for label, center in centers.items()
        }
        exact_anchors = {
            label: matrix_contract(
                left,
                exact_anchor_matrix(
                    target_mean,
                    target_second,
                    true_raw_m21,
                    target_marginal_second,
                    center,
                ),
                right,
            )
            for label, center in centers.items()
        }
        if not np.allclose(
            exact_anchors["oracle_center"],
            true_c21_contribution,
            rtol=2e-7,
            atol=2e-10,
        ):
            raise AssertionError(
                (
                    exact_anchors["oracle_center"],
                    true_c21_contribution,
                )
            )

        baseline_prediction = final.mean(axis=0, dtype=np.float64)
        baseline_mse = float(
            np.mean(np.square(baseline_prediction - targets[-1]))
        )
        method_mses = {}
        anchor_diagnostics = {}
        for center_label, values in pointwise.items():
            exact_anchor = exact_anchors[center_label]
            same_cloud_anchor = np.mean(values, axis=0, dtype=np.float64)
            same_cloud_error = max(
                float(np.linalg.norm(same_cloud_anchor - exact_anchor)),
                1e-30,
            )
            anchors = {
                f"oracle_exact_{center_label}": exact_anchor,
                f"same_cloud_{center_label}": same_cloud_anchor,
                **{
                    f"{label}_{center_label}": anchor
                    for label, anchor in predicted_connected_anchors.items()
                },
            }
            for label, anchor in anchors.items():
                predictions, _ = crossfit_grid(
                    values - anchor,
                    final,
                    args.folds,
                    [args.ridge],
                )
                method_mses[label] = float(
                    np.mean(
                        np.square(
                            predictions[args.ridge] - targets[-1]
                        )
                    )
                )
                anchor_diagnostics[label] = {
                    "relative_to_same_cloud": (
                        0.0
                        if label.startswith("oracle_exact_")
                        else float(
                            np.linalg.norm(anchor - exact_anchor)
                            / same_cloud_error
                        )
                    ),
                    "error": (anchor - exact_anchor).tolist(),
                }
        analytical_flops = analytical_extra_flops(
            late_diagnostics["torch_flops"],
            checkpoint=args.checkpoint,
            target_layer=args.target_layer,
            rank=args.rank,
        )
        record = {
            "index": index,
            "name": name,
            "baseline_mse": baseline_mse,
            "method_mses": method_mses,
            "anchor_diagnostics": anchor_diagnostics,
            "scalar_decomposition": {
                "true_c21_anchor": true_c21_contribution.tolist(),
                "checkpoint_inherited_anchor": (
                    inherited_anchor_contribution.tolist()
                ),
                "late_source_anchor": late_anchor_contribution.tolist(),
            },
            "late_source_diagnostics": late_diagnostics,
            "analytical_extra_flops": analytical_flops,
            "seconds": time.perf_counter() - started,
        }
        records.append(record)
        best = min(method_mses, key=method_mses.get)
        print(
            f"[{index}] base={baseline_mse:.4e} "
            f"best={best}:{method_mses[best] / baseline_mse:.4f}x "
            f"combined(sample-center)="
            f"{method_mses['combined_inherited_scale1_sample_center'] / baseline_mse:.3f}x "
            f"late(sample-center)="
            f"{method_mses['late_source_only_sample_center'] / baseline_mse:.3f}x "
            f"extra={analytical_flops['total_extra'] / 1e9:.2f}B "
            f"({record['seconds']:.1f}s)",
            flush=True,
        )

    summary = summarize(records)
    output = {
        "protocol": {
            "indices": args.indices,
            "checkpoint": args.checkpoint,
            "target_layer": args.target_layer,
            "rotation_seed": args.rotation_seed,
            "rank": args.rank,
            "folds": args.folds,
            "ridge": args.ridge,
            "inherited_scales": args.inherited_scales,
            "dtype": args.dtype,
            "oracle_k2_and_gates": True,
            "control": "radially_homogenized_connected_cubic",
            "deployable_pointwise_center": "sample_center",
            "predicted_target_marginals": False,
            "uses_final_targets_for_construction": False,
            "radial_conversion_corrected": True,
        },
        "summary": summary,
        "records": records,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(output, indent=2))
    print(json.dumps(summary, indent=2), flush=True)
    print(f"wrote {args.out}", flush=True)


if __name__ == "__main__":
    main()
