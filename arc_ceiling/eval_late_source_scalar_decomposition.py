"""Checkpoint-20 scalar K3 transport plus a cheap late-source rollout.

This experiment decomposes the target-layer connected third cumulant into

    K3_29 ~= T_20->29(K3_sample,20) + K3_sources,21:29.

The inherited checkpoint term is never materialized as a 256 x 256 slice.
For two target control directions, the checkpoint cloud is transported once
and contracted directly.  The late term is generated by a factorized K3
rollout initialized with zero K3 at post-activation layer 20.  Oracle mean and
covariance are injected before every late ReLU, so this first experiment is a
ceiling on the source decomposition rather than a free-rollout test.

All target controls use rank two.  The deployed formulation is the radially
homogenized connected-cubic control centered at the Kerdock sample mean, so it
needs only a connected-K3 scalar anchor and no predicted target covariance.
An oracle-mean pointwise center and exact arbitrary-center anchors are retained
only as ceiling diagnostics.  The predeclared combination grid scales only the
inherited checkpoint term: 0.5/0.75 blend, 1.0 additive decomposition, and
1.25 overrelaxation.
"""

